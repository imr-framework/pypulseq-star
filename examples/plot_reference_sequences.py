def _fit_text_font(
    draw: ImageDraw.ImageDraw,
    text: str,
    *,
    max_width: int,
    initial_size: int,
    minimum_size: int = 16,
) -> ImageFont.ImageFont:
    """Choose the largest font that keeps one line inside ``max_width``."""

    for size in range(initial_size, minimum_size - 1, -1):
        font = _font(size)
        box = draw.textbbox((0, 0), text, font=font)
        if box[2] - box[0] <= max_width:
            return font
    return _font(minimum_size)


def _make_composite(
    results: list[PlotResult],
    output_path: Path,
    *,
    dpi: int = 300,
    column_gap: int = 22,
    row_gap: int = 16,
    outer_margin: int = 22,
) -> None:
    """Arrange eight plots in the Figure-4-like 4 x 2 layout."""

    if len(results) != 8:
        raise ValueError("The manuscript composite requires exactly eight panels.")

    loaded = [Image.open(result.png_path).convert("RGB") for result in results]

    # Equalize cell sizes without distorting the underlying timing plots.
    target_width = max(image.width for image in loaded)
    target_height = max(image.height for image in loaded)

    normalized: list[Image.Image] = []
    for image in loaded:
        scale = min(target_width / image.width, target_height / image.height)
        resized = image.resize(
            (round(image.width * scale), round(image.height * scale)),
            Image.Resampling.LANCZOS,
        )
        panel = Image.new("RGB", (target_width, target_height), "white")
        panel.paste(
            resized,
            (
                (target_width - resized.width) // 2,
                (target_height - resized.height) // 2,
            ),
        )
        normalized.append(panel)

    canvas_width = outer_margin * 2 + target_width * 2 + column_gap
    canvas_height = outer_margin * 2 + target_height * 4 + row_gap * 3
    canvas = Image.new("RGB", (canvas_width, canvas_height), "white")

    # First place the eight timing plots.
    panel_positions: list[tuple[int, int]] = []
    for index, panel in enumerate(normalized):
        row, col = divmod(index, 2)
        x = outer_margin + col * (target_width + column_gap)
        y = outer_margin + row * (target_height + row_gap)
        canvas.paste(panel, (x, y))
        panel_positions.append((x, y))

    # Then overlay Figure-4-style panel letters and black command banners.
    draw = ImageDraw.Draw(canvas)
    label_font = _font(max(26, round(target_width * 0.050)), bold=True)

    for result, (x, y) in zip(results, panel_positions):
        spec = result.spec

        # Panel label in the upper-left portion of each cell.
        draw.text(
            (x + round(target_width * 0.018), y + round(target_height * 0.060)),
            spec.label,
            font=label_font,
            fill="black",
        )

        # Command strip: deliberately similar to the current manuscript figure.
        banner_left = x + round(target_width * 0.33)
        banner_right = x + target_width - round(target_width * 0.025)
        banner_top = y + round(target_height * 0.075)
        banner_height = max(34, round(target_height * 0.100))
        banner_bottom = banner_top + banner_height

        draw.rectangle(
            (banner_left, banner_top, banner_right, banner_bottom),
            fill=(24, 24, 24),
        )

        horizontal_padding = max(10, round(target_width * 0.012))
        available_width = banner_right - banner_left - 2 * horizontal_padding
        command_font = _fit_text_font(
            draw,
            spec.command_text,
            max_width=available_width,
            initial_size=max(16, round(target_width * 0.026)),
            minimum_size=12,
        )
        text_box = draw.textbbox((0, 0), spec.command_text, font=command_font)
        text_height = text_box[3] - text_box[1]
        text_y = banner_top + (banner_height - text_height) // 2 - text_box[1]
        draw.text(
            (banner_left + horizontal_padding, text_y),
            spec.command_text,
            font=command_font,
            fill="white",
        )

    canvas.save(output_path, dpi=(dpi, dpi))


def _write_summary(results: list[PlotResult], path: Path) -> None:
    """Write the exact panel definitions and timing-check results."""

    lines = [
        "PyPulseq-Star reference-sequence manuscript comparison",
        "=" * 62,
        "",
    ]

    for result in results:
        lines.append(
            f"{result.spec.label} {result.spec.family}: "
            f"{'PASS' if result.timing_ok else 'FAIL'}"
        )
        lines.append(f"  command label: {result.spec.command_text}")
        for note in result.summary_lines:
            lines.append(f"  {note}")
        if result.timing_report:
            lines.append("  timing report:")
            lines.extend(f"    - {item}" for item in result.timing_report)
        lines.append(f"  figure: {result.png_path}")
        lines.append("")

    path.write_text("\n".join(lines), encoding="utf-8")


# =============================================================================
# CLI / MAIN
