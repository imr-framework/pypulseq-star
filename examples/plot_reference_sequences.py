#!/usr/bin/env python3
"""Generate the manuscript reference-sequence comparison figure.

This script intentionally mirrors the current manuscript Figure 4 layout while
adding FID as a fourth sequence family.  It builds two representative protocol
realizations for each reference sequence and arranges them as a 4 x 2 figure:

    row 1: FID      baseline | protocol edit
    row 2: GRE      baseline | protocol edit
    row 3: EPI      baseline | protocol edit
    row 4: TSE      baseline | protocol edit

The immediate goal is to establish the *content and layout* of the combined
manuscript figure.  Publication typography is deliberately left to the shared
plotter; a later ``publication`` option can improve fonts, line widths, and
other rendering details without changing the figure-generation logic here.

Each cell is generated by the normal sequence demo implementation, resolved,
checked for timing, and rendered by ``Sequence.plot``.  The black command strip
records the protocol change represented by the panel, following the style of
the current manuscript figure as closely as practical.

Run from the ``examples`` directory or repository root:

    python examples/plot_reference_sequences.py

Outputs are written to ``out/reference_sequences`` by default.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable

# Use a non-interactive backend unless the caller explicitly requests display.
if "--show" not in sys.argv:
    import matplotlib

    matplotlib.use("Agg")

import demo_EPI
import demo_FID
import demo_GRE
import demo_TSE
import matplotlib.pyplot as plt
from PIL import Image, ImageDraw, ImageFont

# =============================================================================
# DATA MODEL
# =============================================================================


@dataclass(frozen=True)
class PanelSpec:
    """Definition of one panel in the 4 x 2 manuscript figure."""

    label: str
    family: str
    title: str
    command_text: str
    builder: Callable[[], tuple[Any, tuple[str, ...]]]
    gradient_scale: str | None = None
    repetitions: int = 1
    one_tr: bool = False
    time_range: tuple[float, float] | None = None
    gradient_y_limit: float | None = None


@dataclass(frozen=True)
class PlotResult:
    """Result of building and rendering one panel."""

    spec: PanelSpec
    sequence: Any
    realization: Any
    timing_ok: bool
    timing_report: tuple[str, ...]
    png_path: Path
    summary_lines: tuple[str, ...]


# =============================================================================
# COMMON HELPERS
# =============================================================================


def _resolve_and_check(sequence: Any) -> tuple[Any, bool, tuple[str, ...]]:
    """Resolve one symbolic sequence and normalize its timing report."""

    realization = sequence.resolve()
    ok, report = realization.check_timing()
    return realization, bool(ok), tuple(str(item) for item in report)


def _save_sequence_plot(
    *,
    sequence: Any,
    realization: Any,
    output_path: Path,
    title: str,
    repetitions: int,
    dpi: int,
    width: float,
    height: float,
    gradient_scale: str | None,
    one_tr: bool,
    time_range: tuple[float, float] | None,
    gradient_y_limit: float | None,
    publication: bool,
    show: bool,
) -> None:
    """Render one panel using the normal PyPulseq-Star plotter."""

    plot_kwargs: dict[str, Any] = {
        "realization": realization,
        "repetitions": repetitions,
        "title": title,
        "one_tr": one_tr,
        "figsize": (width, height),
        "dpi": dpi,
        "debug": False,
        "show": show,
        "publication": publication,
    }
    if gradient_scale is not None:
        plot_kwargs["gradient_scale"] = gradient_scale
    if time_range is not None:
        plot_kwargs["time_range"] = time_range

    figure = sequence.plot(**plot_kwargs)
    if figure is None:
        figure = plt.gcf()

    # Use a common gradient scale when a side-by-side amplitude comparison is
    # part of the scientific message. Independent autoscaling can otherwise
    # make different amplitudes look deceptively similar.
    if gradient_y_limit is not None:
        for axis in figure.axes:
            ylabel = axis.get_ylabel().strip().lower()
            if ylabel.startswith(("gx", "gy", "gz")):
                axis.set_ylim(-gradient_y_limit, gradient_y_limit)

    figure.savefig(
        output_path,
        dpi=dpi,
        bbox_inches="tight",
        facecolor="white",
    )

    if show:
        plt.show()
    plt.close(figure)


def _font(size: int, *, bold: bool = False) -> ImageFont.ImageFont:
    """Return a portable font for panel labels and command strips."""

    candidates = (
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
        if bold
        else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/Library/Fonts/Arial Bold.ttf" if bold else "/Library/Fonts/Arial.ttf",
        "C:/Windows/Fonts/arialbd.ttf" if bold else "C:/Windows/Fonts/arial.ttf",
    )

    for candidate in candidates:
        try:
            return ImageFont.truetype(candidate, size=size)
        except OSError:
            continue
    return ImageFont.load_default()


