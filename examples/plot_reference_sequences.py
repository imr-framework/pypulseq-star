def _build_fid(*, num_samples: int, echo_time: float) -> tuple[Any, tuple[str, ...]]:
    """Build one FID realization."""

    overrides = {
        "average": 4,
        "num_samples": num_samples,
        "echo_time": echo_time,
        "repetition_time": 1.0,
    }
    system = demo_FID.define_system_limits()
    protocol = demo_FID.define_protocol(overrides=overrides)
    sequence, te_fill, tr_fill = demo_FID.build_sequence(system, protocol)

    notes = (
        f"num_samples={num_samples}",
        f"TE={echo_time * 1e3:.1f} ms",
        "TR=1000.0 ms",
        f"TE fill={te_fill.eval(sequence) * 1e3:.3f} ms",
        f"TR fill={tr_fill.eval(sequence) * 1e3:.3f} ms",
    )
    return sequence, notes


def _build_gre(*, n_y: int, fov_phase: float) -> tuple[Any, tuple[str, ...]]:
    """Build one scanner-safe GRE realization.

    Keep the scanner-tested read FOV unchanged and vary only the phase FOV.
    This preserves the intended protocol-edit demonstration without driving
    the readout gradient beyond the unchanged hardware limits.
    """

    overrides = {
        "n_y": n_y,
        "fov_phase": fov_phase,
        # Keep the current scanner-tested timing defaults.
        "echo_time": 6e-3,
        "repetition_time": 15e-3,
        "rf_spoiling_increment": 117.0,
    }
    system = demo_GRE.define_system_limits()
    protocol = demo_GRE.define_protocol(orientation="axial", overrides=overrides)
    sequence, te_fill, tr_fill = demo_GRE.build_sequence(
        system,
        protocol,
        orientation="axial",
    )

    notes = (
        "orientation=axial",
        f"n_y={n_y}",
        "FOV read=256.0 mm",
        f"FOV phase={fov_phase * 1e3:.1f} mm",
        "TE=6.0 ms",
        "TR=15.0 ms",
        f"TE fill={te_fill.eval(sequence) * 1e3:.3f} ms",
        f"TR fill={tr_fill.eval(sequence) * 1e3:.3f} ms",
    )
    return sequence, notes


def _build_epi(*, etl: int, fov_phase: float) -> tuple[Any, tuple[str, ...]]:
    """Build one segmented-EPI realization."""

    overrides = {
        "n_y": 64,
        "echo_train_length": etl,
        "fov_phase": fov_phase,
        # Retain current scanner-safe sequence defaults.
        "readout_duration": 640e-6,
        "echo_time": 30e-3,
        "repetition_time": 400e-3,
    }
    system = demo_EPI.define_system_limits()
    protocol = demo_EPI.define_protocol(orientation="axial", overrides=overrides)
    sequence = demo_EPI.build_sequence(system, protocol, orientation="axial")

    notes = (
        "orientation=axial",
        "n_y=64",
        f"ETL={etl}",
        f"FOV phase={fov_phase * 1e3:.1f} mm",
        "readout=640.0 us",
        "TE=30.0 ms",
        "TR=400.0 ms",
    )
    return sequence, notes


def _build_tse(
    *,
    etl: int,
    phase_order: str,
    orientation: str,
) -> tuple[Any, tuple[str, ...]]:
    """Build one TSE realization."""

    overrides = {
        "n_y": 128,
        "echo_train_length": etl,
        "phase_encode_order": phase_order,
        # Preserve the scanner-tested timing/RF defaults in the demo.
        "TE_effective": 64e-3,
        "repetition_time": 2.0,
        "refocusing_flip_angle": 180.0,
    }
    system = demo_TSE.define_system_limits()
    protocol = demo_TSE.define_protocol(
        orientation=orientation,
        overrides=overrides,
    )
    sequence, first_refocus_fill, pre_readout_fill, tr_fill = demo_TSE.build_sequence(
        system,
        protocol,
        orientation=orientation,
    )

    notes = (
        f"orientation={orientation}",
        "n_y=128",
        f"ETL={etl}",
        f"order={phase_order}",
        "effective TE=64.0 ms",
        "TR=2000.0 ms",
        f"first-refocus fill={first_refocus_fill.eval(sequence) * 1e3:.3f} ms",
        f"pre-readout fill={pre_readout_fill.eval(sequence) * 1e3:.3f} ms",
        f"TR fill={tr_fill.eval(sequence) * 1e3:.3f} ms",
    )
    return sequence, notes


