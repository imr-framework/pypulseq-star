def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Build the eight reference-sequence manuscript panels and combine "
            "them into a Figure-4-like 4 x 2 layout."
        )
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("out/reference_sequences"),
        help="Directory for panel PNGs, composite PNG, and run summary.",
    )
    parser.add_argument("--dpi", type=int, default=300)
    parser.add_argument("--composite-dpi", type=int, default=300)
    parser.add_argument("--panel-width", type=float, default=12.0)
    parser.add_argument("--panel-height", type=float, default=6.8)
    parser.add_argument(
        "--show",
        action="store_true",
        help="Display individual figures interactively in addition to saving them.",
    )
    parser.add_argument(
        "--no-publication",
        action="store_true",
        help="Disable publication-mode typography for A/B comparison.",
    )
    parser.add_argument(
        "--no-composite",
        action="store_true",
        help="Generate the eight individual panels only.",
    )
    parser.add_argument(
        "--continue-on-failure",
        action="store_true",
        help="Generate all panels even if one timing check fails.",
    )
    return parser


def main() -> int:
    args = _parser().parse_args()
    output_dir: Path = args.output_dir
    output_dir.mkdir(parents=True, exist_ok=True)

    results: list[PlotResult] = []
    failures: list[str] = []

    for spec in _panel_specs():
        slug = spec.family.lower().replace(" ", "_").replace("-", "_")
        panel_slug = spec.label.rstrip(")")
        png_path = output_dir / f"{panel_slug}_{slug}_timing.png"

        print(f"\n{'=' * 76}")
        print(f"Building panel {spec.label} {spec.family}")
        print(spec.command_text)
        print("=" * 76)

        try:
            sequence, notes = spec.builder()
            realization, timing_ok, timing_report = _resolve_and_check(sequence)

            print(f"Timing check: {'PASS' if timing_ok else 'FAIL'}")
            for item in timing_report:
                print(f"  {item}")

            _save_sequence_plot(
                sequence=sequence,
                realization=realization,
                output_path=png_path,
                title=spec.title,
                repetitions=spec.repetitions,
                dpi=args.dpi,
                width=args.panel_width,
                height=args.panel_height,
                gradient_scale=spec.gradient_scale,
                one_tr=spec.one_tr,
                time_range=spec.time_range,
                gradient_y_limit=spec.gradient_y_limit,
                publication=not args.no_publication,
                show=args.show,
            )
            print(f"Wrote timing diagram: {png_path}")

            results.append(
                PlotResult(
                    spec=spec,
                    sequence=sequence,
                    realization=realization,
                    timing_ok=timing_ok,
                    timing_report=timing_report,
                    png_path=png_path,
                    summary_lines=notes,
                )
            )

            if not timing_ok:
                failures.append(f"{spec.label} {spec.family}")

        except Exception as exc:
            failures.append(f"{spec.label} {spec.family}: {exc}")
            print(f"Panel generation failed: {exc}")
            if not args.continue_on_failure:
                raise

    summary_path = output_dir / "reference_sequence_summary.txt"
    _write_summary(results, summary_path)
    print(f"\nWrote run summary: {summary_path}")

    if not args.no_composite:
        if len(results) == 8:
            composite_path = output_dir / "reference_sequence_capabilities.png"
            _make_composite(
                results,
                composite_path,
                dpi=args.composite_dpi,
            )
            print(f"Wrote 4 x 2 composite: {composite_path}")
        else:
            print("Composite skipped because not all eight panels were generated.")

    if failures:
        print("\nPanel/timing failures:")
        for failure in failures:
            print(f"  - {failure}")
        if not args.continue_on_failure:
            return 1

    print("\nAll requested reference-sequence panels were generated.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
